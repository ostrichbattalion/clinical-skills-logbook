/** Writes ../js/config.js so the static pages know which API and Cognito pool to talk to. */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { backendRoot, readOutputs } from './outputs.js';

const { values } = parseArgs({ options: { stage: { type: 'string' } } });
const o = readOutputs(values.stage);
const config = { apiUrl: o.ApiUrl, region: o.Region, userPoolId: o.UserPoolId, userPoolClientId: o.UserPoolClientId };
const file = join(backendRoot, '../js/config.js');
writeFileSync(file, `// Generated by backend/scripts/write-frontend-config.ts. Safe to commit: these values are public.\nwindow.LOGBOOK_CONFIG = ${JSON.stringify(config, null, 2)};\n`);
console.log(`Wrote ${file}`);
